int KnnModel_Score(const float *input)
{
    float x[KNN_MODEL_NUM_INPUTS];
    for (int f = 0; f < KNN_MODEL_NUM_INPUTS; f++) {
        x[f] = input[f];
    }

    /* Os K vizinhos mais próximos, ordenados por distância crescente. */
    float best_d[KNN_MODEL_K];
    int   best_c[KNN_MODEL_K];
    for (int j = 0; j < KNN_MODEL_K; j++) {
        best_d[j] = INFINITY;
        best_c[j] = 0;
    }

    for (int i = 0; i < KNN_MODEL_NUM_SAMPLES; i++) {
        float d = 0.0f;
        for (int f = 0; f < KNN_MODEL_NUM_INPUTS; f++) {
            float t = x[f] - s_knn_model_train_X[i][f];
            d += t * t;
        }
        if (d < best_d[KNN_MODEL_K - 1]) {
            int j = KNN_MODEL_K - 1;
            while (j > 0 && best_d[j - 1] > d) {   /* '>' estrito: empate mantém o índice menor */
                best_d[j] = best_d[j - 1];
                best_c[j] = best_c[j - 1];
                j--;
            }
            best_d[j] = d;
            best_c[j] = (int)s_knn_model_train_y[i];
        }
    }

    int votes[KNN_MODEL_NUM_CLASSES];
    for (int c = 0; c < KNN_MODEL_NUM_CLASSES; c++) votes[c] = 0;
    for (int j = 0; j < KNN_MODEL_K; j++) votes[best_c[j]]++;

    int best = 0;
    for (int c = 1; c < KNN_MODEL_NUM_CLASSES; c++)
        if (votes[c] > votes[best]) best = c;   /* empate: menor índice de classe */
    return best;
}

int KnnModel_DecideLigarGPRS(float bateria_pct, float taxa_normalizada)
{
    float input[KNN_MODEL_NUM_INPUTS];

    input[0] = bateria_pct;
    input[1] = taxa_normalizada;

    return (KnnModel_Score(input) == KNN_MODEL_CLASSE_LIGA) ? 1 : 0;
}
